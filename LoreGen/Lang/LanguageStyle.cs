namespace LoreGen.Lang
{
    /// <summary>
    /// How a world's places are named.
    /// </summary>
    public enum LanguageStyle
    {
        /// <summary>
        /// Names that read like those in fantasy and historical fiction, from blends of familiar naming traditions
        /// (see <see cref="CommonLanguage"/>).
        /// </summary>
        Common,

        /// <summary>
        /// Names built sound by sound from random phonetic rules, which sound foreign and unfamiliar
        /// (see <see cref="PhoneticLanguage"/>).
        /// </summary>
        Phonetic
    }
}
